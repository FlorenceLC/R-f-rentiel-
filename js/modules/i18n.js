let _lang = 'fr';

export function setLang(lang) {
  if (TRANSLATIONS[lang]) _lang = lang;
}

export function getLang() { return _lang; }

export function t(key, fallback) {
  return TRANSLATIONS[_lang]?.[key]
    ?? TRANSLATIONS['fr']?.[key]
    ?? fallback
    ?? key;
}

/** Shorthand for origin label */
export function originLabel(origin) {
  if (!origin) return '—';
  if (origin === 'FR') return `🇫🇷 ${t('request.entity.fr')}`;
  if (origin === 'DE') return `🇩🇪 ${t('request.entity.de')}`;
  return origin;
}

/** Visibility label */
export function visibilityLabel(v) {
  if (v === 'FR') return `🇫🇷 ${t('cu.visibility.fr')}`;
  if (v === 'DE') return `🇩🇪 ${t('cu.visibility.de')}`;
  return `🌍 ${t('cu.visibility.common')}`;
}
